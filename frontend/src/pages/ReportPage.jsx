import { useEffect, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { CheckCircle2, Download, FileText, Link2, MoveLeft, OctagonX, QrCode } from 'lucide-react'
import AppLayout from '../components/AppLayout'
import { historyApi } from '../services/api'

export default function ReportPage() {
  const { analysisId } = useParams()
  const [report, setReport] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const featureEvidence = report?.features
    ? Object.entries(report.features).filter(([, value]) => value && value !== 0).slice(0, 5)
    : []
  const InputIcon = report?.input_type === 'URL' ? Link2 : report?.input_type === 'QR' ? QrCode : FileText
  const decisionLabel = report?.decision === 'BLOCK' ? 'Do Not Proceed' : report?.decision === 'WARN' ? 'Use Caution' : 'Allow'

  useEffect(() => {
    const loadReport = async () => {
      setLoading(true)
      setError('')
      try {
        let id = analysisId
        if (!id) {
          const history = await historyApi.list(1, 1)
          id = history.data.data.items[0]?.id
        }
        if (!id) {
          setError('No analysis is available to report yet.')
          return
        }
        const response = await historyApi.get(id)
        setReport(response.data.data)
      } catch (err) {
        setError(err.response?.data?.detail || 'Unable to load this analysis report.')
      } finally {
        setLoading(false)
      }
    }
    loadReport()
  }, [analysisId])

  return (
    <AppLayout title="Analysis report">
      {loading ? <div className="card panel empty-state">Loading report...</div> : error ? <div className="card panel report-empty"><p>{error}</p><Link className="primary-btn" to="/analysis">Start an analysis</Link></div> : report && <article className="card report-sheet">
        <header className="report-heading"><div><span className="tiny-label">ANALYSIS REPORT</span><h2>{report.input_type} Analysis Report</h2><p>{new Date(report.created_at).toLocaleString()}</p></div><button className="primary-btn print-button" type="button" onClick={() => window.print()}><Download size={15} /> Download PDF</button></header>
        <div className="report-url"><span className="report-input-icon"><InputIcon size={16} /></span><div><strong>{report.input_type} Analysis Report</strong><span>{report.input_content}</span></div></div>
        <section className="report-summary">
          <div className="report-score"><span>Risk Score</span><strong>{report.risk_score}<small> / 100</small></strong><span className={`badge ${(report.risk_level || '').toLowerCase().replace(/ /g, '-')}`}>{report.risk_level}</span></div>
          <div className="report-fact"><span>Classification</span><strong>{report.classification}</strong></div>
          <div className="report-fact"><span>Decision</span><strong className={report.decision === 'BLOCK' ? 'decision-block' : 'decision-allow'}>{report.decision === 'BLOCK' ? <OctagonX size={15} /> : <CheckCircle2 size={15} />}{decisionLabel}</strong></div>
        </section>
        <div className="report-columns">
          <section className="report-section"><h3>Evidence</h3>{report.evidence?.length || featureEvidence.length ? <ul className="evidence-list">{(report.evidence || []).map((item, index) => <li key={`evidence-${index}`}>{item}</li>)}{featureEvidence.map(([key, value]) => <li key={key}>{key.replace(/_/g, ' ')}: {Array.isArray(value) ? value.join(', ') : String(value)}</li>)}</ul> : <p className="muted">No detector evidence was recorded for this analysis.</p>}</section>
          <div className="report-analysis-right"><section className="report-section"><h3>Explanation</h3><p>{report.explanation || 'This result is based on the available risk signals.'}</p></section><section className="report-recommendation"><h3>Recommendation</h3><p>{report.recommendation}</p></section></div>
        </div>
        <footer className="report-footer"><Link to="/history"><MoveLeft size={14} /> Back to history</Link><span>Generated by SafeScan</span></footer>
      </article>}
    </AppLayout>
  )
}